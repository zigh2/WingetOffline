using System.Text;

namespace WingetOffline.Core.Install;

/// <summary>
/// يولّد سكربت PowerShell مستقلاً يثبّت مجلد مثبّتات دون الحاجة للتطبيق نفسه
/// (فكرة "Generate script" في winstall و Install-Offline.ps1 في WingetBatch).
/// المسارات نسبية لمجلد السكربت عندما تكون المثبّتات داخله، فيمكن نقل المجلد كاملاً.
/// </summary>
public static class InstallScriptBuilder
{
    public static string Build(IEnumerable<(IndexedInstaller Item, CatalogInstaller Info)> entries, string scriptDir)
    {
        var steps = new List<(InstallPlan Plan, CatalogInstaller Info, string File)>();
        foreach (var (item, info) in entries)
        {
            try { steps.Add((InstallPlanner.Plan(item.FilePath, info, new InstallOptions()), info, item.FilePath)); }
            catch (NotSupportedException) { /* نوع غير مدعوم (PWA) */ }
        }

        var sb = new StringBuilder();
        if (steps.Any(s => s.Plan.NeedsElevation)) sb.AppendLine("#Requires -RunAsAdministrator");
        sb.AppendLine($"# Generated by WingetOffline on {DateTime.Now:yyyy-MM-dd HH:mm}");
        sb.AppendLine($"# {steps.Count} package(s):");
        foreach (var s in steps) sb.AppendLine($"#   {s.Info.PackageId} {s.Info.Version} ({s.Info.Type}, {s.Info.Arch})");
        sb.AppendLine();
        sb.AppendLine("$script:failed = @()");
        sb.AppendLine();
        sb.AppendLine(@"function Invoke-Step([string]$Name, [string]$File, [string]$Arguments) {
    Write-Host ""==> $Name""
    try {
        $sp = @{ FilePath = $File; Wait = $true; PassThru = $true; ErrorAction = 'Stop' }
        if ($Arguments) { $sp.ArgumentList = $Arguments }
        $p = Start-Process @sp
        if (@(0, 1641, 3010) -contains $p.ExitCode) { Write-Host ""    OK (exit code $($p.ExitCode))"" -ForegroundColor Green }
        else { Write-Host ""    FAILED (exit code $($p.ExitCode))"" -ForegroundColor Red; $script:failed += $Name }
    } catch { Write-Host ""    ERROR: $($_.Exception.Message)"" -ForegroundColor Red; $script:failed += $Name }
}

function Invoke-Portable([string]$Name, [string]$Source, [string]$Target) {
    Write-Host ""==> $Name""
    try {
        New-Item -ItemType Directory -Force -Path $Target | Out-Null
        if ($Source -like '*.zip') { Expand-Archive -LiteralPath $Source -DestinationPath $Target -Force }
        else { Copy-Item -LiteralPath $Source -Destination $Target -Force }
        Write-Host '    OK' -ForegroundColor Green
    } catch { Write-Host ""    ERROR: $($_.Exception.Message)"" -ForegroundColor Red; $script:failed += $Name }
}
");

        var root = Path.GetFullPath(scriptDir).TrimEnd('\\', '/') + Path.DirectorySeparatorChar;
        foreach (var (plan, info, file) in steps)
        {
            var full = Path.GetFullPath(file);
            var fileExpr = full.StartsWith(root, StringComparison.OrdinalIgnoreCase)
                ? $"(Join-Path $PSScriptRoot '{Esc(full[root.Length..])}')"
                : $"'{Esc(full)}'";
            var name = $"{info.PackageId} {info.Version}".Trim();

            sb.AppendLine($"$f = {fileExpr}");
            if (plan.Kind == PlanKind.Portable)
            {
                var folder = Path.GetFileName(plan.Target!.TrimEnd('\\', '/'));
                sb.AppendLine($"Invoke-Portable -Name '{Esc(name)}' -Source $f -Target (Join-Path $env:LOCALAPPDATA 'WingetOffline\\Portable\\{Esc(folder)}')");
            }
            else
            {
                if (plan.Interactive) sb.AppendLine("# no silent switch known for this installer: it will show its own window");
                var fileArg = plan.FileName == file ? "$f" : $"'{Esc(plan.FileName)}'";
                sb.AppendLine($"Invoke-Step -Name '{Esc(name)}' -File {fileArg} -Arguments ({Expr(plan.Arguments, file)})");
            }
            sb.AppendLine();
        }

        sb.AppendLine("if ($script:failed.Count -gt 0) {");
        sb.AppendLine("    Write-Host \"`nFailed: $($script:failed -join ', ')\" -ForegroundColor Red");
        sb.AppendLine("    exit 1");
        sb.AppendLine("}");
        sb.AppendLine("Write-Host \"`nAll done.\" -ForegroundColor Green");
        return sb.ToString();
    }

    private static string Esc(string s) => s.Replace("'", "''");

    /// <summary>يحوّل نص الوسيطات إلى تعبير PowerShell يستبدل مسار الملف بالمتغير $f.</summary>
    private static string Expr(string text, string filePath)
    {
        if (string.IsNullOrEmpty(text)) return "''";
        var parts = text.Split(filePath, StringSplitOptions.None);
        return string.Join(" + $f + ", parts.Select(p => "'" + Esc(p) + "'"));
    }
}
